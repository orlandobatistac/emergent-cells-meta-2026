"""Emergent Cells Studio: a local, runnable agent research product.

The visualization has separate observer (simulator truth) and agent channels.
Agent policy never receives simulator positions, goal coordinates, or maps.
Language UX optionally uses an EXISTING Ollama foundation model; it is not
generated by, or evidence of equivalence with, the experimental cells.

Install product extras: pip install -e ".[studio]"
Run: python run.py studio --host 127.0.0.1 --port 8765
"""
import argparse
import json
from pathlib import Path
import re
import threading
from typing import Any
from urllib import error, request

from .belief_navigation import BeliefExplorer
from .event_cells import EventDrivenCells
from .local_value_cells import LocalValueCells
from .stochastic_motor import SlipWorld, calibrate
from .sensor_world import SensorEpisode

DIRECTIONS=("north","south","west","east")
RATES=(.75,.60,.90,.45)
MODEL="qwen2.5-coder:7b"
UI_PATH=Path(__file__).with_name("studio.html")


class Laboratory:
    """A single interactive scientific mission with a strict policy boundary."""

    def __init__(self):
        self._guard=threading.RLock()
        self.reset(seed=13001, changed=False, stochastic=False, controller="event")

    def reset(self, *, seed: int, changed: bool, stochastic: bool,
              controller: str="event"):
        if not isinstance(seed,int) or isinstance(seed,bool) or not 0<=seed<=10_000_000:
            raise ValueError("seed must be an integer in [0,10000000]")
        if type(changed) is not bool or type(stochastic) is not bool:
            raise ValueError("world flags must be booleans")
        if controller not in ("event","local"):
            raise ValueError("controller must be event or local")
        with self._guard:
            self.seed=seed
            self.changed=changed
            self.stochastic=stochastic
            self.controller=controller
            self.done=False
            self.history=[]
            self.observer_messages=0
            if stochastic:
                self.world=SlipWorld(seed,rates=RATES,motion_noise=.2,
                                     floor_noise=.15,changed=changed,limit=160)
                learned=calibrate(seed,RATES,actions=120,
                                  tick_error=.2,floor_error=.15).estimate()
                self.policy=BeliefExplorer(seed,rates=learned,width=8,rounds=2,
                                           aggregation="best")
            else:
                self.world=SensorEpisode(changed=changed,limit=160)
                self.policy=(EventDrivenCells(seed,budget=80)
                             if controller=="event" else
                             LocalValueCells(seed,mode="diffusion",rounds=10))
            self.reading=self.world.reset(seed) if stochastic else self.world.reset(seed,goals=3)
            if stochastic:self.policy.reset(self.reading)
            return self._status_locked()

    def _world_metrics(self):
        env=self.world._env if self.stochastic else self.world
        return env.metrics()

    def _map(self):
        if self.stochastic:
            p=self.policy.beam[0]
            return p.walls, p.position, len(self.policy.beam)
        if self.controller=="event":
            return {pos:tuple(c.walls) for pos,c in self.policy.cells.items()},self.policy.position,1
        return {pos:tuple(a not in actions for a in range(4))
                for pos,actions in self.policy.open_actions.items()}, self.policy.position,1

    def _status_locked(self):
        cells,pos,hypotheses=self._map()
        reading=self.reading
        metrics=self._world_metrics()  # Observer-only *display* metrics.
        current={
            "walls":list(reading.walls),
            "nearby_target":list(reading.nearby_target),
            "floor_signal":reading.floor_signal,
            "previous_reward":round(reading.previous_reward,4),
        }
        if self.stochastic:
            current["motion_tick"]=reading.motion_tick
        return {
            "seed":self.seed, "changed":self.changed,
            "stochastic":self.stochastic,"controller":self.controller,
            "done":self.done,
            "steps":metrics["steps"], "waypoints":metrics["waypoints"],
            "completed":bool(metrics["completed"]),
            "action_limit":160,"goals":3,
            "current_reading":current,
            "estimated_position":list(pos),
            "hypotheses":hypotheses,
            "faults_injected":(0 if self.stochastic or self.controller!="event"
                               else self.policy.failures_injected),
            "cells_relearned":(0 if self.stochastic or self.controller!="event"
                               else self.policy.reobserved_failed_cells),
            "discovered_cells":len(cells),
            "cells":[{"x":x,"y":y,"walls":list(walls)}
                     for (x,y),walls in sorted(cells.items())],
            "messages":(self.policy.message_ops if self.stochastic else
                        self.policy.messages_delivered if self.controller=="event" else
                        self.policy.local_message_updates),
            "latest_actions":self.history[-12:],
            "policy":("multi-hypothesis belief explorer" if self.stochastic
                      else "event-driven local cells" if self.controller=="event"
                      else "synchronous local value propagation"),
            "policy_disclosure":"Engineered local planning and relative motor priors; not a general learned AGI.",
            "language_model":MODEL,
            "foundation_model_distinct_from_cells":True,
        }

    def status(self):
        with self._guard:
            return self._status_locked()

    def step(self, count=1):
        if type(count) is not int or not 1<=count<=160:
            raise ValueError("count must be an integer in [1,160]")
        with self._guard:
            for _ in range(count):
                if self.done:break
                old=self.reading
                action=self.policy.act(old)
                if self.stochastic:
                    self.reading,self.done=self.world.step(action)
                    self.policy.observe(old,self.reading,action)
                else:
                    self.reading,_,self.done=self.world.step(action)
                    self.policy.observe(self.reading)
                self.history.append({
                    "step":self._world_metrics()["steps"],
                    "direction":DIRECTIONS[action],
                    "reward":round(self.reading.previous_reward,3),
                })
            return self._status_locked()

    def inject_cell_failure(self):
        """Erase a visited noncurrent cell. Models memory loss, not a PC failure."""
        with self._guard:
            if self.stochastic or self.controller!="event":
                raise ValueError("Cell failure simulation requires event-driven cells")
            candidates=[p for p in self.policy.cells if p!=self.policy.position]
            if not candidates:
                raise ValueError("Explore at least two cells first")
            candidate=max(sorted(candidates),key=lambda p:self.policy.cells[p].visits)
            self.policy.drop_cell(candidate)
            return self._status_locked()

    def local_command(self, message):
        """Safe deterministic commands, without running model-generated code."""
        q=message.strip().lower()
        if q in ("status","estado","progress","progreso","stats","estadísticas"):
            s=self.status()
            return "Mission status: %s/3 goals, %s/160 actions, %s known cells, %s internal hypotheses." % (
                s["waypoints"],s["steps"],s["discovered_cells"],s["hypotheses"]),s
        if q.startswith(("reset","reinicia","reiniciar","restart")):
            s=self.reset(seed=self.seed,changed=self.changed,stochastic=self.stochastic,
                         controller=self.controller)
            return "Mission restarted with seed %s."%s["seed"],s
        if q.startswith(("run","explore","avanza","explora","ejecuta","continue","continúa","autopilot","auto")):
            n=re.search(r"\b(\d{1,3})\b",q)
            count=min(160,int(n.group(1))) if n else 20
            if count<1:count=1
            s=self.step(count)
            return ("Executed through action %s. Completed %s/3 goals; %s local locations discovered." %
                    (s["steps"],s["waypoints"],s["discovered_cells"])),s
        return None

    def ask_local_model(self, message, timeout=90):
        state=self.status()
        safe={k:state[k] for k in
              ("seed","stochastic","steps","waypoints","done",
               "discovered_cells","hypotheses","policy")}
        system=("You are Emergent Cells Studio's local research assistant. "
                "Your language generation is powered by an existing Ollama Qwen model, "
                "NOT by the experimental cellular architecture. Never conflate them. "
                "No evidence supports human-level or ChatGPT-level capabilities. "
                "Explain partial observability and local memory accurately. "
                "The scientific policy is engineered in the current prototype. "
                "You have no shell, browser, remote execution or arbitrary tool privileges. "
                "For actions, ask the user to use 'run 20', 'status' or 'reset'. "
                "Reply compactly in the language of the user. "
                "Current agent-only-safe status: "+json.dumps(safe))
        payload={"model":MODEL,"stream":False,
                 "prompt":system+"\nUser: "+message[:1000]+"\nAssistant:",
                 "options":{"temperature":.25,"num_ctx":2048,"num_predict":260},
                 "keep_alive":"5m"}
        data=json.dumps(payload).encode("utf-8")
        req=request.Request("http://127.0.0.1:11434/api/generate",
                            data=data,headers={"Content-Type":"application/json"},
                            method="POST")
        try:
            with request.urlopen(req,timeout=timeout) as res:
                reply=json.load(res)
            return str(reply.get("response","")).strip() or "No response from local model."
        except (OSError,ValueError) as exc:
            return ("Local language model unavailable. The scientific simulator "
                    "continues to operate offline. Try 'run 20', 'status' or 'reset'. "
                    f"(Local model error: {type(exc).__name__})")


def create_app(lab=None):
    """Import web dependencies only when the optional studio is launched."""
    from fastapi import FastAPI, HTTPException
    from fastapi.responses import HTMLResponse
    from pydantic import BaseModel, Field
    app=FastAPI(title="Emergent Cells Studio",version="0.1.0",docs_url=None,
                redoc_url=None)
    laboratory=lab if lab is not None else Laboratory()

    class NewMission(BaseModel):
        seed: int = Field(ge=0,le=10000000)
        changed: bool = False
        stochastic: bool = False
        controller: str = "event"

    class StepBatch(BaseModel):
        count: int = Field(ge=1,le=160)

    class Chat(BaseModel):
        message: str = Field(min_length=1,max_length=1000)

    @app.get("/",response_class=HTMLResponse)
    def home():
        return UI_PATH.read_text(encoding="utf-8")

    @app.get("/api/health")
    def health():
        return {"ok":True,"service":"Emergent Cells Studio","local_only":True}

    @app.get("/api/status")
    def status():
        return laboratory.status()

    @app.post("/api/reset")
    def reset(data:NewMission):
        try:return laboratory.reset(seed=data.seed,changed=data.changed,
                                    stochastic=data.stochastic,
                                    controller=data.controller)
        except ValueError as exc:raise HTTPException(status_code=422,detail=str(exc))

    @app.post("/api/step")
    def step(data:StepBatch):
        return laboratory.step(data.count)

    @app.post("/api/fault")
    def fault():
        try:return laboratory.inject_cell_failure()
        except ValueError as exc:raise HTTPException(status_code=422,detail=str(exc))

    @app.post("/api/chat")
    def chat(data:Chat):
        result=laboratory.local_command(data.message)
        if result is not None:
            answer,state=result
            return {"answer":answer,"status":state,"powered_by":"local engine"}
        return {"answer":laboratory.ask_local_model(data.message),
                "status":laboratory.status(),
                "powered_by":"optional separate local Ollama model"}
    return app


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--host",default="127.0.0.1")
    parser.add_argument("--port",type=int,default=8765)
    parser.add_argument("--no-browser",action="store_true")
    a=parser.parse_args()
    if a.host not in ("127.0.0.1","localhost","::1"):
        parser.error("Studio binds to loopback only. External hosts prohibited.")
    import uvicorn
    if not a.no_browser:
        import webbrowser
        webbrowser.open(f"http://127.0.0.1:{a.port}/")
    uvicorn.run(create_app(),host=a.host,port=a.port,log_level="warning")


if __name__=="__main__":
    main()
