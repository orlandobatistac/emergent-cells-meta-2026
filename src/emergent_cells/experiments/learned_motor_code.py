"""Learn motor command orientation from local wall/contact observations.

The environment secretly permutes four motor commands. The learner has NO
position, goal, trajectory or map labels: it sees a directional four-wall
sensor before an action and a local bump/contact outcome afterward.

Important remaining structure: the learner is given compass-aligned wall
channels and a hard-coded hypothesis class of the 24 motor permutations.
This calibrates a motor-code mapping, NOT arbitrary emergent odometry.
"""
from __future__ import annotations

import argparse
import itertools
import json
from pathlib import Path
import random
import time

from .local_value_cells import LocalValueCells
from .sensor_world import SensorEpisode
from .recurrent_state import GeneratedMaze

PERMUTATIONS = tuple(itertools.permutations(range(4)))


class MotorCodeWorld:
    """Simulation-only motor permutation with a local contact sensor."""

    def __init__(self, mapping, *, changed=False, procedural_seed=None,
                 contact_flip_probability=0., seed=0):
        if tuple(sorted(mapping)) != (0, 1, 2, 3):
            raise ValueError("mapping must permute four directions")
        self._mapping = tuple(mapping)
        self._env = SensorEpisode(changed=changed, limit=160)
        if procedural_seed is not None:
            self._env._maze = GeneratedMaze(procedural_seed)
        self._rng = random.Random(seed * 19 + 101)
        self._contact_flip_probability = contact_flip_probability
        self.reading = None

    def reset(self, seed, goals=3):
        self.reading = self._env.reset(seed, goals=goals)
        return self.reading

    def step(self, motor_command):
        if motor_command not in range(4):
            raise ValueError("invalid motor command")
        if self.reading is None:
            raise RuntimeError("reset before step")
        # The bumper is a LEGITIMATE LOCAL SENSOR, generated by simulator:
        direction = self._mapping[motor_command]
        contact = bool(self.reading.walls[direction])
        self.reading, reward, done = self._env.step(direction)
        if self._rng.random() < self._contact_flip_probability:
            contact = not contact
        return self.reading, contact, reward, done


class MotorCodeLearner:
    """Bayesian evidence accumulation over 24 candidate motor mappings."""

    def __init__(self, *, error_rate=.05):
        if not 0 < error_rate < .5:
            raise ValueError("error_rate must be between zero and 0.5")
        self.log_score = [0.] * len(PERMUTATIONS)
        self.error_rate = error_rate
        self.samples = 0

    def observe(self, walls, motor_command, contact):
        if len(walls) != 4 or motor_command not in range(4):
            raise ValueError("invalid local sensor reading")
        import math
        yes = math.log(1. - self.error_rate)
        no = math.log(self.error_rate)
        for i, candidate in enumerate(PERMUTATIONS):
            predicted = bool(walls[candidate[motor_command]])
            self.log_score[i] += yes if predicted == contact else no
        self.samples += 1

    def estimate(self):
        best = max(range(len(PERMUTATIONS)), key=lambda i: self.log_score[i])
        return PERMUTATIONS[best]

    def posterior_confidence(self):
        import math
        best = max(self.log_score)
        normalized = [math.exp(x - best) for x in self.log_score]
        return max(normalized) / sum(normalized)


def learn_mapping(seed, mapping, *, calibration_steps=160, noise=0.0):
    """Calibration episodes use a source world and random local motor probes.

    Source resets diversify wall observations, a simulator privilege.
    The calibration learner receives only four local wall bits and bumper.
    """
    learner = MotorCodeLearner(error_rate=max(.02, noise if noise else .02))
    rng = random.Random(seed * 193 + 307)
    world = MotorCodeWorld(mapping, seed=seed, contact_flip_probability=noise)
    steps = 0
    while steps < calibration_steps:
        reading = world.reset(seed * 1009 + steps, goals=3)
        for _ in range(min(24, calibration_steps - steps)):
            command = rng.randrange(4)
            current_walls = reading.walls
            reading, contact, _, done = world.step(command)
            learner.observe(current_walls, command, contact)
            steps += 1
            if done:
                break
    return learner


def play(seed, mapping, estimated_mapping, *, changed=False,
         procedural=False, rounds=10):
    world = MotorCodeWorld(mapping, changed=changed,
                           procedural_seed=(seed if procedural else None),
                           seed=seed)
    reading = world.reset(seed, goals=3)
    controller = LocalValueCells(seed, mode="diffusion", rounds=rounds)
    inverse = {direction: command
               for command, direction in enumerate(estimated_mapping)}
    while True:
        desired_direction = controller.act(reading)
        command = inverse[desired_direction]
        reading, contact, reward, done = world.step(command)
        # The existing controller updates assuming its intended direction
        # was executed; under a wrong mapping this memory becomes inaccurate.
        # That is precisely what the no-calibration ablation tests.
        controller.observe(reading)
        if done:
            break
    return {
        **world._env.metrics(),
        "cells": len(controller.open_actions),
        "message_updates": controller.local_message_updates,
    }


def benchmark(seeds, *, calibration_steps=160, noise=.05,
              rounds=10, procedural=False):
    if not seeds or len(seeds) != len(set(seeds)):
        raise ValueError("distinct nonempty seeds required")
    start = time.process_time()
    records = []
    for seed in seeds:
        rng = random.Random(seed * 433 + 19)
        mapping = PERMUTATIONS[rng.randrange(len(PERMUTATIONS))]
        learner = learn_mapping(seed, mapping,
                                calibration_steps=calibration_steps,
                                noise=noise)
        estimate = learner.estimate()
        for changed in ((False,) if procedural else (False, True)):
            for mode in ("learned_mapping", "known_mapping", "uncalibrated_identity"):
                selected = (estimate if mode == "learned_mapping" else
                            mapping if mode == "known_mapping" else
                            (0, 1, 2, 3))
                result = play(seed, mapping, selected, changed=changed,
                              procedural=procedural, rounds=rounds)
                records.append({
                    "seed": seed, "changed": changed, "mode": mode,
                    "actual_motor_mapping": mapping,
                    "estimated_motor_mapping": estimate,
                    "mapping_correct": estimate == mapping,
                    "confidence": learner.posterior_confidence(),
                    **result,
                })
    summary = {}
    for changed in ((False,) if procedural else (False, True)):
        label = "procedural" if procedural else "changed" if changed else "stable"
        summary[label] = {}
        for mode in ("learned_mapping", "known_mapping", "uncalibrated_identity"):
            items = [r for r in records if r["changed"] == changed
                     and r["mode"] == mode]
            summary[label][mode] = {
                "success_rate": sum(r["completed"] for r in items)/len(items),
                "mean_waypoints": sum(r["waypoints"] for r in items)/len(items),
                "mean_steps": sum(r["steps"] for r in items)/len(items),
            }
    return {"protocol": {
        "seeds": seeds, "calibration_steps_per_seed": calibration_steps,
        "contact_noise_probability": noise,
        "compass_aligned_wall_sensor": True,
        "hypothesis_class": "all 24 known four-direction permutations",
        "source_random_reset_privilege": True,
        "policy_global_pose_or_map_input": False,
        "value_diffusion_engineered": True,
        "centralized_python_scheduler": True,
        "separate_calibration_budget": True,
        "test_procedural_maps": procedural,
        "test_rounds": rounds,
        "cpu_process_seconds": time.process_time() - start,
    }, "calibration": {
        "exact_mapping_rate": sum(
            r["mapping_correct"] for r in records
            if r["mode"] == "learned_mapping" and not r["changed"]
        ) / len(seeds),
        "mean_posterior_confidence": sum(
            r["confidence"] for r in records
            if r["mode"] == "learned_mapping" and not r["changed"]
        ) / len(seeds),
    }, "summary": summary, "records": records}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seeds", default="501,502,503,504,505")
    parser.add_argument("--calibration-steps", type=int, default=160)
    parser.add_argument("--noise", type=float, default=.05)
    parser.add_argument("--rounds", type=int, default=10)
    parser.add_argument("--procedural", action="store_true")
    parser.add_argument("--output", default="")
    p = parser.parse_args()
    if p.calibration_steps < 8:
        parser.error("calibration needs at least eight local probes")
    data = benchmark(
        [int(x) for x in p.seeds.split(",")],
        calibration_steps=p.calibration_steps,
        noise=p.noise, rounds=p.rounds, procedural=p.procedural)
    if p.output:
        target = Path(p.output)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(data, indent=2), encoding="utf-8")
    print(json.dumps({
        "calibration": data["calibration"],
        "summary": data["summary"],
        "cpu_process_seconds": data["protocol"]["cpu_process_seconds"],
        "output": p.output,
    }, indent=2))


if __name__ == "__main__":
    main()
